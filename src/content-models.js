let lecturePromise;
export function ensureModelDialog() {
  if (document.querySelector("#concept-model")) return;
  const dialog = document.createElement("dialog");
  dialog.id = "concept-model";
  dialog.innerHTML =
    '<div class="model-header"><div><div class="eyebrow">ИНТЕРАКТИВНАЯ МОДЕЛЬ ЛЕКЦИИ</div><h2 id="model-title"></h2></div><button id="model-close" aria-label="Вернуться к карте">×</button></div><div id="model-content"></div>';
  document.body.append(dialog);
  dialog.querySelector("#model-close").onclick = () => dialog.close();
}
export async function openConceptModel(node, data) {
  ensureModelDialog();
  const dialog = document.querySelector("#concept-model"),
    model = modelCatalog[node.model];
  if (!model) return;
  const content = dialog.querySelector("#model-content");
  dialog.querySelector("#model-title").textContent = model.title;
  content.innerHTML = `<p class="model-question">${esc(model.question)}</p><div class="model-concept"><strong>${esc(node.label)}</strong><p>${esc(node.definition)}</p></div><div class="model-grid"><form id="model-controls">${model.controls()}<button type="button" id="model-reset" class="secondary">Сбросить параметры</button></form><div id="model-result" aria-live="polite"></div></div><p class="concept-boundary"><b>Ограничение выбранного понятия:</b> ${esc(node.limit)}</p><details id="model-sources"><summary>Источник: слайды ${node.provenance.slides.join(", ")} и заметки преподавателя</summary><div id="source-text">Загрузка исходных заметок…</div></details><details><summary>Научные источники лекции (не новая независимая проверка)</summary><p>${data.references.map((r) => `<a href="${r.url}" target="_blank" rel="noreferrer">[${r.id}] ${esc(r.title)}</a>`).join("<br>")}</p></details>`;
  const laboratory = laboratoryForConcept("emotions", node.id);
  if (laboratory) {
    const button = document.createElement("button");
    button.type = "button";
    button.id = "open-lab-from-model";
    button.className = "lab-card-entry lab-model-entry";
    button.textContent = "Сопоставить объяснения в Model Laboratory ↗";
    button.onclick = () =>
      openLaboratory(laboratory.id, {
        conceptId: node.id,
        conceptLabel: node.label,
      });
    content.querySelector(".model-concept").after(button);
  }
  const form = content.querySelector("form"),
    history = [];
  const initial =
    {
      suppression: { strategy: "response" },
      reappraisal: { strategy: "meaning" },
      attend: { strategy: "attention" },
      action: { goal: "action" },
      experience: { level: "experience" },
      category: { context: "unknown" },
    }[node.id] || {};
  for (const [name, value] of Object.entries(initial)) {
    const control = form.elements.namedItem(name);
    if (control?.tagName === "SELECT") {
      for (const option of control.options)
        option.defaultSelected = option.value === value;
      control.value = value;
    }
  }
  const update = () => {
    const state = {};
    form.querySelectorAll("[name]").forEach((el) => {
      state[el.name] = el.type === "checkbox" ? el.checked : el.value;
      const output = form.querySelector(`[data-value="${el.name}"]`);
      if (output) output.textContent = el.value;
    });
    content.querySelector("#model-result").innerHTML = model.render(
      state,
      history,
    );
  };
  form.oninput = update;
  form.onchange = update;
  form.onsubmit = (e) => e.preventDefault();
  form.querySelector("#model-reset").onclick = () => {
    form.reset();
    history.length = 0;
    update();
  };
  form.querySelector("[data-step]")?.addEventListener("click", () => {
    history.push(form.elements.orientation.value);
    update();
  });
  form.querySelector("[data-reset]")?.addEventListener("click", () => {
    history.length = 0;
    update();
  });
  update();
  if (!dialog.open) dialog.showModal();
  dialog.scrollTop = 0;
  dialog.dataset.model = node.model;
  dialog.dataset.node = node.id;
  lecturePromise ??= fetch("/sources/emotions/lecture.json").then((r) => {
    if (!r.ok) throw Error("Не удалось загрузить заметки");
    return r.json();
  });
  try {
    const lecture = await lecturePromise;
    if (dialog.dataset.node !== node.id) return;
    content.querySelector("#source-text").innerHTML =
      lecture
        .filter((s) => node.provenance.slides.includes(s.number))
        .map(
          (s) =>
            `<article><h4>Слайд ${s.number}</h4><pre>${esc(s.text)}</pre><h4>Заметки преподавателя</h4><pre>${esc(s.notes)}</pre></article>`,
        )
        .join("") +
      '<p><a href="/sources/emotions/scenario.md" target="_blank">Полный сценарий и комментарии</a></p>';
  } catch (e) {
    content.querySelector("#source-text").textContent = e.message;
  }
}
